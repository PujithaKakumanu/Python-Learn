# strings provide a method called upper() which is used to convert all the characters in the string to uppercase.
# string methods are used to perform various operations on strings.
# General syntax of string methods is: string.methodname()

s = "Hello my name is Pujitha Kakumanu"
print(s.upper())
print(s[0:5].upper()+s[5:]) # converting only the first 5 characters to uppercase
