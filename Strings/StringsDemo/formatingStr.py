# f formatting of strings using f-strings.
# General syntax: f"string {value1} string {value2} ..."

# formating of strings using format() method.
# General syntax: string.format(value1, value2, ...)

name = "Kakumanu Pujitha"
age = 22
print(f"My name is {name} and I am {age} years old.") # using f-strings
print("My name is {} and I am {} years old.".format(name,age)) # using format() method
