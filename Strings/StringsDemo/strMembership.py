# Membership of a string using in and not in operators.
# General syntax: 'substring' in string (returns True if substring is found, otherwise False)
# General syntax: 'substring' not in string (returns True if substring is not found, otherwise False)

s = "kakumanu Pujitha"
print('kakumanu' in s) #True
print('Poojitha' in s) #False
print('Poojitha' not in s) #True
print('a'in s) #True